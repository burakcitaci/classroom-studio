CREATE TABLE classrooms (
  id UUID PRIMARY KEY,
  title TEXT NOT NULL,
  subject TEXT NOT NULL,
  grade TEXT NOT NULL,
  school_year TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  language TEXT NOT NULL CHECK (language IN ('en', 'de')),
  archived INTEGER NOT NULL DEFAULT 0 CHECK (archived IN (0, 1)),
  updated TIMESTAMPTZ NOT NULL
);

CREATE TABLE lessons (
  id UUID PRIMARY KEY,
  class_id UUID NOT NULL REFERENCES classrooms(id),
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  goals TEXT NOT NULL DEFAULT '',
  lesson_date TEXT,
  position BIGINT GENERATED BY DEFAULT AS IDENTITY
);

CREATE TABLE documents (
  id UUID PRIMARY KEY,
  updated TIMESTAMPTZ NOT NULL,
  edit INTEGER NOT NULL DEFAULT 0 CHECK (edit >= 0),
  ready INTEGER NOT NULL DEFAULT 0 CHECK (ready IN (0, 1)),
  settings JSON NOT NULL,
  draft JSON,
  class_id UUID REFERENCES classrooms(id),
  lesson_id UUID REFERENCES lessons(id)
);

CREATE TABLE sources (
  id UUID PRIMARY KEY,
  doc_id UUID NOT NULL REFERENCES documents(id),
  name TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('file', 'note')),
  file_ext TEXT,
  status TEXT NOT NULL CHECK (status IN ('extracting', 'indexing', 'ready', 'error')),
  preview TEXT NOT NULL DEFAULT '',
  error TEXT,
  retryable INTEGER NOT NULL DEFAULT 0 CHECK (retryable IN (0, 1)),
  position BIGINT GENERATED BY DEFAULT AS IDENTITY
);

CREATE TABLE chunks (
  id UUID PRIMARY KEY,
  source_id UUID NOT NULL REFERENCES sources(id),
  ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
  text TEXT NOT NULL,
  UNIQUE(source_id, ordinal)
);

CREATE TABLE revisions (
  id UUID PRIMARY KEY,
  doc_id UUID NOT NULL REFERENCES documents(id),
  number INTEGER NOT NULL CHECK (number > 0),
  kind TEXT NOT NULL CHECK (kind IN ('AI', 'Teacher', 'Ready', 'Restored')),
  created TIMESTAMPTZ NOT NULL,
  draft JSON NOT NULL,
  settings JSON NOT NULL,
  job_id UUID,
  UNIQUE(doc_id, number)
);

CREATE TABLE jobs (
  id UUID PRIMARY KEY,
  doc_id UUID NOT NULL REFERENCES documents(id),
  request_key UUID NOT NULL,
  input JSON NOT NULL,
  base_edit INTEGER NOT NULL,
  created TIMESTAMPTZ NOT NULL,
  started TIMESTAMPTZ,
  stage TEXT NOT NULL CHECK (stage IN ('queued', 'retrieving', 'generating', 'validating', 'succeeded', 'failed')),
  audit JSON NOT NULL,
  position BIGINT GENERATED BY DEFAULT AS IDENTITY,
  UNIQUE(doc_id, request_key)
);

CREATE INDEX lessons_class ON lessons(class_id, lesson_date);
CREATE INDEX documents_class ON documents(class_id, updated DESC);
CREATE INDEX documents_lesson ON documents(lesson_id);
CREATE INDEX sources_document ON sources(doc_id);
CREATE INDEX revisions_document ON revisions(doc_id, number DESC);
CREATE INDEX jobs_document ON jobs(doc_id, created DESC);
CREATE INDEX jobs_stage ON jobs(stage, created, position);
